void MX_GPIO_Init(void)
{

  /* GPIO Ports Clock Enable */
  __HAL_RCC_GPIOD_CLK_ENABLE();
  __HAL_RCC_GPIOA_CLK_ENABLE();
  __HAL_RCC_GPIOB_CLK_ENABLE();

  /* USER CODE BEGIN GPIO_Init 2 */

  /* TIM1 break input (PB12): active LOW emergency shut-down.
   * Internal pull-up keeps the inverter running when the pin is left open;
   * pull it to GND (fault contact / button / over-current detector) to kill
   * all six gate outputs in hardware within one timer clock cycle. */
#if (INVERTER_ENABLE_BREAK == 1)
  {
    GPIO_InitTypeDef GPIO_InitStruct = {0};
    GPIO_InitStruct.Pin = GPIO_PIN_12;
    GPIO_InitStruct.Mode = GPIO_MODE_INPUT;
    GPIO_InitStruct.Pull = GPIO_PULLUP;
    HAL_GPIO_Init(GPIOB, &GPIO_InitStruct);
  }
#endif /* INVERTER_ENABLE_BREAK */

  /* USER CODE END GPIO_Init 2 */
}

